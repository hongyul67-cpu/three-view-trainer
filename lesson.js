var seq = 0;
/* 도구의 그리기 함수를 캔버스에 부른다.
   figHtml() 은 innerHTML 로 바로 꽂히므로 다음 프레임이면 캔버스가 화면에 있다 —
   그때라야 크기를 잴 수 있어 제 크기로 그려진다. */
function cv(fn) {
  var id = 'lcv' + (++seq);
  requestAnimationFrame(function () {
    var el = document.getElementById(id);
    if (el) { try { fn(el); } catch (e) {} }
  });
  return '<canvas id="' + id + '"></canvas>';
}
function lay(key, method, opt) {
  return cv(function (el) {
    var F = window.TFIG, S = shapes()[key];
    if (F && F.drawLayout && S) F.drawLayout(el, S, method || 'third', opt || {});
  });
}
function iso(key) {
  return cv(function (el) {
    var F = window.TFIG, S = shapes()[key];
    if (F && F.drawIso && S) F.drawIso(el, S, {});
  });
}
